#include <iostream>
using namespace std;

int main()
{
    // Different data types
    int age = 20;
    float height = 5.8f;
    double salary = 25000.50;
    char grade = 'A';
    bool passed = true;
    string name = "Veda";

    // Display the values
    cout << "Name   : " << name << endl;
    cout << "Age    : " << age << endl;
    cout << "Height : " << height << endl;
    cout << "Salary : " << salary << endl;
    cout << "Grade  : " << grade << endl;
    cout << "Passed : " << passed << endl;

    return 0;
}
